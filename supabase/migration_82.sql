-- 3. Alquileres --------------------------------------------------------------
create table if not exists public.alq_alquileres (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity,
  buzo_id uuid not null references public.viajes_buzos(id) on delete restrict,
  fecha date not null,                   -- fecha de alquiler
  dias integer not null default 3 check (dias in (3, 6)),   -- normal o doble
  devolver date not null,                -- fecha + dias
  factura text,                          -- No. de factura del sistema de la tienda
  notas text,
  creado_por uuid references auth.users(id) on delete set null default auth.uid(),
  creado_por_nombre text,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create index if not exists alq_alquileres_buzo_idx on public.alq_alquileres (buzo_id);
create index if not exists alq_alquileres_fecha_idx on public.alq_alquileres (fecha desc);

create table if not exists public.alq_items (
  id uuid primary key default gen_random_uuid(),
  alquiler_id uuid not null references public.alq_alquileres(id) on delete cascade,
  codigo text not null,
  tipo text,
  descripcion text,
  precio numeric not null default 0,     -- precio por 3 días (de ese día)
  total numeric not null default 0,      -- lo que se cobró (el doble si es doble)
  devuelto_en timestamptz,
  devuelto_por text,                     -- quién lo trajo (si no fue el cliente)
  recibido_por text,                     -- quién de la tienda lo recibió
  mora_dias integer,
  mora numeric,
  nota text
);
create index if not exists alq_items_alquiler_idx on public.alq_items (alquiler_id);
create index if not exists alq_items_afuera_idx on public.alq_items (upper(codigo)) where devuelto_en is null;

