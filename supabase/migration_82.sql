-- migration_82.sql -- V57. App Alquiler. Se puede correr más de una vez.
-- No borra ni cambia datos que ya existan.
--
--   1. Quién puede: el Titular, los administradores y quien tenga
--      "acceso_alquiler" (Accesos a apps). Precios y equipos: Titular,
--      administradores, o quien tenga "alq_equipos".
--   2. Base de equipos: los tanques (T, TX) y reguladores (RE) son los
--      mismos de App Interno ("128. sí"): solo se les agrega el precio de
--      alquiler. Lo demás (caretas, BCD, chapaletas, cinturones, bolsos,
--      wetsuits...) va en alq_equipos.
--   3. Los alquileres: la persona es la misma base de Buceos y Estudiantes
--      ("129. sí"); cada equipo es una línea que se puede devolver aparte
--      y con su propia mora ("130": "el recargo debe de ser por artículo").
--   4. La bitácora de Alquiler.
-- =====================================================================

-- 1. Quién puede -------------------------------------------------------------
create or replace function public.alq_puede(p_clave text default null)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((
    select p.es_titular
        or p.is_admin
        or (
          coalesce((p.permisos->>'acceso_alquiler')::boolean, false)
          and (p_clave is null or coalesce((p.permisos->>p_clave)::boolean, false))
        )
      from public.profiles p
     where p.id = auth.uid()
  ), false)
$$;
grant execute on function public.alq_puede(text) to authenticated;

-- 2. Equipos -----------------------------------------------------------------
alter table public.tanques_alquiler add column if not exists precio_alquiler numeric;      -- por 3 días
